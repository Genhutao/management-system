package plugins

// trusted_keys.go —— 编译进主程序的**出厂信任锚**。
//
// 这里放的是**公钥**（base64 的 32 字节 Ed25519 公钥），不是私钥。私钥由使用方本人
// 离线保管，本仓库里不存在、也不该由开发过程生成或代管（计划 §3.2 已拍板）。
//
// 为什么内置一把之外还要有 plugin_keys/ 目录（见 sign.go 的 LoadAnchors）：
// 内置锚保证最坏情况下——运维误删公钥目录、或那台机器被人写过的痕迹还没查清——
// 加载器仍然只认我们出厂时打进去的那位开发者。目录是补充，不是替代。
//
// 怎么加一位开发者（使用方操作，两步）：
//  1. 他自己在保管私钥的那台机器上跑 `go run ./cmd/pluginctl keygen`，
//     把打印出来的 kid 与公钥抄下来；
//  2. 公钥填进下面这个切片（或先放进运行目录的 plugin_keys/developer-<kid>.pub 试跑），
//     重新编译发布包。
//
// 内置锚换一把钥匙 = 重编一次主程序，这是刻意的：动摇根信任的改动不该是
// "往服务器丢个文件"就能做到的。
//
// 留空也是安全的：一把可信公钥都没有时，**任何插件都进不了可授权列表**
// （失败关闭，见 AnchorSet.Verify）。所以这份文件不必在没准备好密钥时先塞占位值。
